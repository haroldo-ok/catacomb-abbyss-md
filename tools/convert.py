def gen_color(rgb):
    def lvl(v):
        return {0x00: 0, 0x55: 2, 0x57: 2, 0xAA: 5, 0xAB: 5, 0xFF: 7}.get(v, (v * 7 + 127) // 255)
    r, g, b = (lvl(c) for c in rgb)
    return (b << 9) | (g << 5) | (r << 1)


