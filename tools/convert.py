def c_bytes(name, data, typ='u8', per_line=24, static=False, align=None):
    out = []
    attr = ' __attribute__((aligned(%d)))' % align if align else ''
    out.append('%sconst %s %s[%d]%s = {' % ('static ' if static else '', typ, name, len(data), attr))
    for i in range(0, len(data), per_line):
        out.append('  ' + ','.join(str(v) for v in data[i:i + per_line]) + ',')
    out.append('};')
    return '\n'.join(out) + '\n'


def c_words(name, data, typ='u16', static=False):
    return c_bytes(name, data, typ, 16, static)


def c_longs(name, data, typ='u32', static=False):
    out = ['%sconst %s %s[%d] = {' % ('static ' if static else '', typ, name, len(data))]
    for i in range(0, len(data), 8):
        out.append('  ' + ','.join('0x%08X' % v for v in data[i:i + 8]) + ',')
    out.append('};')
    return '\n'.join(out) + '\n'


def c_string(s):
    r = '"'
    for ch in s:
        o = ord(ch)
        if ch == '"' or ch == '\\':
            r += '\\' + ch
        elif 32 <= o < 127:
            r += ch
        else:
            r += '\\%03o' % (o & 0xFF)
    return r + '"'


def write(name, text):
    p = os.path.join(GEN, name)
    old = open(p).read() if os.path.exists(p) else None
    if old != text:
        open(p, 'w').write(text)


