# 3-D tables (BuildTables() float maths reproduced, plus ray-cast tables)
# --------------------------------------------------------------------------

def convert_tables():
    import math
    import numpy as np
    ANGLES = 360
    sintab = [0] * (ANGLES + ANGLES // 4 + 1)
    angle = np.float32(0.0)
    anglestep = np.float32(np.float32(3.141592657) / np.float32(2) / np.float32(90))
    for i in range(0, 91):
        value = int(65536 * math.sin(float(angle)))
        sintab[i] = value
        sintab[i + ANGLES] = value
        sintab[ANGLES // 2 - i] = value
        sintab[ANGLES - i] = -value
        sintab[ANGLES // 2 + i] = -value
        angle = np.float32(angle + anglestep)
    out = HEADER
    out += 'const s32 sintable_init[%d] = {%s};\n' % (len(sintab), ','.join(str(v) for v in sintab))
    hdr = ['extern const s32 sintable_init[451];']

    FINE = 3600
    invc, invs, cs, sn = [], [], [], []
    for a in range(FINE):
        r = a * 2 * math.pi / FINE
        c = math.cos(r)
        sv = math.sin(r)
        cs.append(int(round(c * 65535)))
        sn.append(int(round(sv * 65535)))
        invc.append(min(0x00FFFFFF, int(65536.0 / abs(c))) if abs(c) > 1e-9 else 0x00FFFFFF)
        invs.append(min(0x00FFFFFF, int(65536.0 / abs(sv))) if abs(sv) > 1e-9 else 0x00FFFFFF)
    out += 'const u32 ray_invcos[FINEANGLES] = {%s};\n' % ','.join(str(v) for v in invc)
    out += 'const u32 ray_invsin[FINEANGLES] = {%s};\n' % ','.join(str(v) for v in invs)
    out += 'const s32 ray_cos[FINEANGLES] = {%s};\n' % ','.join(str(v) for v in cs)
    out += 'const s32 ray_sin[FINEANGLES] = {%s};\n' % ','.join(str(v) for v in sn)
    hdr += ['#define FINEANGLES 3600',
            'extern const u32 ray_invcos[FINEANGLES];', 'extern const u32 ray_invsin[FINEANGLES];',
            'extern const s32 ray_cos[FINEANGLES];', 'extern const s32 ray_sin[FINEANGLES];']
    # per 2-pixel column: angle offset and forward-distance factor, matching
    # the TransformPoint() projection (scale = 145, centre pixel 159)
    scale = ((65536 // 320) * 65536) // (65536 + 26214)
    colang, colcos = [], []
    for c in range(160):
        t = ((2 * c + 1) - 159) * scale / 65536.0
        a = -math.atan(t)
        colang.append(int(round(a * FINE / (2 * math.pi))))
        colcos.append(int(round(math.cos(a) * 65535)))
    colk = [int((1 << 24) / (scale * (cv / 65535.0))) for cv in colcos]
    out += 'const u32 col_k[160] = {%s};\n' % ','.join(str(v) for v in colk)
    hdr += ['extern const u32 col_k[160];']
    out += 'const s16 col_angle[160] = {%s};\n' % ','.join(str(v) for v in colang)
    out += 'const u16 col_cos[160] = {%s};\n' % ','.join(str(v) for v in colcos)
    hdr += ['extern const s16 col_angle[160];', 'extern const u16 col_cos[160];',
            '#define PROJ_SCALE %d' % scale]
    # horizontal sprite sampling: src column = (offset * hinv[s]) >> 16
    hinv = [0] + [int(32 * 65536 // s) for s in range(1, MAXSCALE + 1)]
    out += 'const u32 scale_hinv[MAXSCALE+1] = {%s};\n' % ','.join(str(v) for v in hinv)
    hdr += ['extern const u32 scale_hinv[MAXSCALE+1];']
    return out, hdr

