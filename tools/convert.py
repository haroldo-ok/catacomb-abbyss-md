def pix_rows(g, c):
    w, h = g.pic_size(c)
    pix = egaimg.deplane(g.chunk(c), w, h)
    if c == 5:                  # STATUSPIC
        pix = patch_status(list(pix), w * 8)
    return pix, w * 8, h


# The status bar's key hints "ESC-OPTIONS" / "F1-HELP" become joypad hints,
# drawn in the same 6-pixel shadowed lettering.
HINT_FONT = {
    'S': ['.##', '#..', '.#.', '..#', '..#', '##.'],
    'T': ['###', '.#.', '.#.', '.#.', '.#.', '.#.'],
    'A': ['.#.', '#.#', '#.#', '###', '#.#', '#.#'],
    'R': ['##.', '#.#', '#.#', '##.', '#.#', '#.#'],
    'M': ['#...#', '##.##', '#.#.#', '#...#', '#...#', '#...#'],
    'E': ['###', '#..', '##.', '#..', '#..', '###'],
    'N': ['#..#', '##.#', '#.##', '#..#', '#..#', '#..#'],
    'U': ['#.#', '#.#', '#.#', '#.#', '#.#', '###'],
    'B': ['##.', '#.#', '##.', '#.#', '#.#', '##.'],
    'F': ['###', '#..', '##.', '#..', '#..', '#..'],
    'I': ['#', '#', '#', '#', '#', '#'],
    '-': ['....', '....', '####', '....', '....', '....'],
}


def patch_status(pix, w):
    def put(x, y, c):
        pix[y * w + x] = c

    def draw(x0, x1, parts):
        width = sum(sum(len(HINT_FONT[ch][0]) + 1 for ch in t) for t, col in parts) + 1
        x = x0 + (x1 - x0 + 1 - width) // 2
        for t, col in parts:
            for ch in t:
                g = HINT_FONT[ch]
                for gy, row in enumerate(g):
                    for gx, v in enumerate(row):
                        if v == '#':
                            put(x + gx + 1, 70 + gy + 1, 0)
                for gy, row in enumerate(g):
                    for gx, v in enumerate(row):
                        if v == '#':
                            put(x + gx, 70 + gy, col)
                x += len(g[0]) + 1

    for (x0, x1, parts) in ((14, 64, [('START-', 12), ('MENU', 9)]),
                            (252, 302, [('B-', 12), ('FIRE', 9)])):
        for y in range(70, 77):
            for x in range(x0, x1 + 1):
                put(x, y, 8)
        draw(x0, x1, parts)
    return pix


def pack_columns(pix, w, h, mask=None):
    """Column-major 'long' layout: for each 8-pixel column, h longs (8 px of
    4bpp). With mask: returns (mask_longs, data_longs) where mask nibble 0xF
    means keep destination."""
    data, msk = [], []
    for bx in range(w // 8):
        for y in range(h):
            v = 0
            m = 0
            for x in range(8):
                p = pix[y * w + bx * 8 + x]
                v = (v << 4) | p
                transparent = mask[y * w + bx * 8 + x] if mask is not None else 0
                m = (m << 4) | (0xF if transparent else 0)
                if transparent:
                    v &= ~0xF
            data.append(v)
            msk.append(m)
    return (msk, data) if mask is not None else data


def convert_graphics():
    g = iddata.Graphics()
    out = HEADER
    hdr = []

    # ---- full pics used by the 2D code (stored column-major longs)
    pics = list(range(4, FIRSTSCALEPIC))
    table = []
    for c in pics:
        pix, w, h = pix_rows(g, c)
        longs = pack_columns(pix, w, h)
        out += c_longs('pic%d_data' % c, longs, static=True)
        table.append((c, w // 8, h))
    out += 'const PicDef pic_table[NUMPICDEFS] = {\n'
    for c in range(0, FIRSTSCALEPIC):
        ent = [t for t in table if t[0] == c]
        if ent:
            out += '  {%d,%d,pic%d_data},\n' % (ent[0][1], ent[0][2], c)
        else:
            out += '  {0,0,NULL},\n'
    out += '};\n'
    hdr.append('#define NUMPICDEFS %d' % FIRSTSCALEPIC)

    # ---- walls: 64 columns x 64 rows, column major; every texel is a word
    # (4 equal pixels) so that the byte scalers draw 2-pixel columns and the
    # word scalers draw two identical columns at once
    walls = bytearray()
    nwalls = LASTWALLPIC - FIRSTWALLPIC
    for c in range(FIRSTWALLPIC, LASTWALLPIC):
        if c == FIRSTWALLPIC:
            walls += bytes(8192)
            continue
        pix, w, h = pix_rows(g, c)
        for x in range(64):
            for y in range(64):
                p = pix[y * 64 + x]
                walls.append(p * 0x11)
                walls.append(p * 0x11)
    out += c_bytes('wall_tex', walls, align=2)
    hdr.append('#define NUMWALLPICS %d' % nwalls)
    hdr.append('extern const u8 wall_tex[%d];' % len(walls))

    # ---- scaled shapes: column segment lists
    blob = bytearray()
    offs = []
    for c in range(FIRSTSCALEPIC, FIRSTWALLPIC):
        if c == FIRSTSCALEPIC:
            offs.append(0xFFFFFFFF)
            continue
        pix, w, h = pix_rows(g, c)
        img = [[BACKGROUNDPIX] * 64 for _ in range(64)]
        for y in range(64):
            for x in range(w):
                img[y][x] = pix[y * w + x]
        cols = [x for x in range(64) if any(img[y][x] != BACKGROUNDPIX for y in range(64))]
        if not cols:
            offs.append(0xFFFFFFFF)
            continue
        first, last = cols[0], cols[-1]
        width = last - first + 1
        start = len(blob)
        if start & 1:
            blob.append(0)
            start += 1
        offs.append(start)
        blob += struct.pack('>H', width)
        table_pos = len(blob)
        blob += bytes(2 * width)
        for x in range(first, last + 1):
            struct.pack_into('>H', blob, table_pos + 2 * (x - first), len(blob) - start)
            y = 0
            while y < 64:
                while y < 64 and img[y][x] == BACKGROUNDPIX:
                    y += 1
                if y >= 64:
                    break
                y0 = y
                while y < 64 and img[y][x] != BACKGROUNDPIX:
                    y += 1
                blob += bytes([y0, y - y0])
                blob += bytes(img[r][x] * 0x11 for r in range(y0, y))
            blob.append(0xFF)
    out += c_bytes('shape_blob', blob, align=2)
    out += c_longs('shape_offsets', offs)
    hdr.append('#define NUMSCALEPICS %d' % (FIRSTWALLPIC - FIRSTSCALEPIC))
    hdr.append('extern const u8 shape_blob[%d];' % len(blob))
    hdr.append('extern const u32 shape_offsets[NUMSCALEPICS];')

    # ---- tile8 (104 x 8 rows) and masked tile8 (12)
    t8 = g.chunk(iddata.STARTTILE8)
    longs = []
    for t in range(iddata.NUMTILE8):
        pix = egaimg.deplane(t8[t * 32:(t + 1) * 32], 1, 8)
        longs += pack_columns(pix, 8, 8)
    out += c_longs('tile8_data', longs)
    hdr.append('#define NUMTILE8 %d' % iddata.NUMTILE8)
    hdr.append('extern const u32 tile8_data[NUMTILE8*8];')
    t8m = g.chunk(iddata.STARTTILE8M)
    longs = []
    for t in range(iddata.NUMTILE8M):
        blk = t8m[t * 40:(t + 1) * 40]
        mask = egaimg.deplane(blk, 1, 8, 1)
        pix = egaimg.deplane(blk, 1, 8, 4, 8)
        m, d = pack_columns(pix, 8, 8, mask)
        for i in range(8):
            longs += [m[i], d[i]]
    out += c_longs('tile8m_data', longs)
    hdr.append('#define NUMTILE8M %d' % iddata.NUMTILE8M)
    hdr.append('extern const u32 tile8m_data[NUMTILE8M*16];')

    # ---- NORTHICONSPR: masked sprite, 1 byte x 5 rows
    spr = g.chunk(iddata.STARTSPRITES)
    sw, sh = g.spritetable[0][0], g.spritetable[0][1]
    psz = sw * sh
    mask = egaimg.deplane(spr, sw, sh, 1)
    pix = egaimg.deplane(spr, sw, sh, 4, psz)
    out += c_bytes('northicon_pix', [0xFF if mask[i] else pix[i] for i in range(sw * 8 * sh)])
    hdr.append('#define NORTHICON_W %d' % (sw * 8))
    hdr.append('#define NORTHICON_H %d' % sh)
    hdr.append('extern const u8 northicon_pix[NORTHICON_W*NORTHICON_H];')

    # ---- hand (HAND1PICM): masked pic, column-major (mask,data) long pairs
    hw, hh = g.picmtable[0]
    hd = g.chunk(HAND1PICM)
    mask = egaimg.deplane(hd, hw, hh, 1)
    pix = egaimg.deplane(hd, hw, hh, 4, hw * hh)
    m, d = pack_columns(pix, hw * 8, hh, mask)
    longs = []
    for i in range(len(m)):
        longs += [m[i], d[i]]
    out += c_longs('hand_data', longs)
    hdr.append('#define HAND_WBYTES %d' % hw)
    hdr.append('#define HAND_H %d' % hh)
    hdr.append('extern const u32 hand_data[HAND_WBYTES*HAND_H*2];')

    # ---- font
    f = g.chunk(iddata.STARTFONT)
    fh = struct.unpack_from('<h', f, 0)[0]
    loc = struct.unpack_from('<256h', f, 2)
    wid = list(f[514:770])
    out += c_bytes('font_widths', wid)
    out += c_words('font_locs', [l if l > 0 else 0 for l in loc])
    out += c_bytes('font_data', f)
    hdr.append('#define FONT_HEIGHT %d' % fh)
    hdr.append('extern const u8 font_widths[256];')
    hdr.append('extern const u16 font_locs[256];')
    hdr.append('extern const u8 font_data[%d];' % len(f))

    # ---- level description texts (LEVEL1TEXT..LEVEL20TEXT)
    texts = []
    for c in range(605, 625):
        t = g.chunk(c).decode('latin1').replace('\r', '')
        lines = t.split('\n')
        # textstarts[0] = start, then each subsequent line
        lines = (lines + [''] * 27)[:27]
        texts.append(lines)
    out += 'const char * const level_texts[20][27] = {\n'
    for lines in texts:
        out += '  {' + ','.join(c_string(adapt_text(s.rstrip())) for s in lines) + '},\n'
    out += '};\n'
    hdr.append('extern const char * const level_texts[20][27];')

    # piracy screen chunk is a text-mode screen; kept for completeness
    out += c_bytes('piracy_screen', g.chunk(625))
    hdr.append('extern const u8 piracy_screen[4000];')

    hdr.append('typedef struct { u16 wbytes, height; const u32 *data; } PicDef;')
    hdr.append('extern const PicDef pic_table[NUMPICDEFS];')
    return out, hdr, g


def adapt_text(s):
    """Level texts that name DOS keys are reworded for the joypad."""
    rep = {
        'For openers, read the Help (F1), then...': 'For openers, read the Help (START), then...',
        'Be ready with the CTRL and Z keys...': 'Be ready with the B and A buttons...',
    }
    return rep.get(s, s)


