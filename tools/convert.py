"""Catacomb Abyss -> Sega Genesis asset converter.

Reads the original shareware v1.13 data files (EGAGRAPH.ABS, GAMEMAPS.ABS,
AUDIO.ABS, HELP.TXT, the Gamer's Edge shell/intro files) plus the header
tables linked into CATABYSS.EXE, and writes:

  src/gen/*.c / *.h   C arrays (big-endian, ROM resident)
  src/gen/scalers.s   compiled wall scalers (68000 asm)
  res/*.png, res/*.wav, res/assets.res   rescomp inputs (intro images, sfx)

Usage: convert.py <project dir>
"""
