def build_renderer():
    exe = os.path.join(HERE, 'build', 'adlib_render')
    src = os.path.join(HERE, 'adlib_render.c')
    opl = os.environ.get('NUKED_OPL3', '/home/claude/src/Nuked-OPL3')
    os.makedirs(os.path.dirname(exe), exist_ok=True)
    if not os.path.exists(exe) or os.path.getmtime(exe) < os.path.getmtime(src):
        subprocess.check_call(['cc', '-O2', '-o', exe, src, os.path.join(opl, 'opl3.c'),
                               '-I', opl, '-lm'])
    return exe


def write_wav(path, samples, rate):
    data = bytes(samples)
    hdr = b'RIFF' + struct.pack('<I', 36 + len(data)) + b'WAVE'
    hdr += b'fmt ' + struct.pack('<IHHIIHH', 16, 1, 1, rate, rate, 1, 8)
    hdr += b'data' + struct.pack('<I', len(data))
    open(path, 'wb').write(hdr + data)


def resample(s16, src_rate, dst_rate):
    """Box-filtered decimation of 16-bit samples to unsigned 8-bit."""
    out = []
    ratio = src_rate / dst_rate
    n = int(len(s16) / ratio)
    for i in range(n):
        a = int(i * ratio)
        b = max(a + 1, int((i + 1) * ratio))
        seg = s16[a:b]
        v = sum(seg) / len(seg)
        v = int(round(v / 256.0)) + 128
        out.append(min(255, max(0, v)))
    return out


def pc_render(ch):
    """PC speaker sound: one byte per 140 Hz tick, value s -> timer divisor
    s*60 (1193181 Hz clock), 0 = silence (SDL_PCService)."""
    length = struct.unpack_from('<I', ch, 0)[0]
    data = ch[6:6 + length]
    out = []
    phase = 0.0
    per = PCM_RATE / 140.0
    acc = 0.0
    for s in data:
        acc += per
        n = int(acc)
        acc -= n
        if s:
            f = 1193181.0 / (s * 60)
            for k in range(n):
                phase += f / PCM_RATE
                out.append(128 + (34 if (phase % 1.0) < 0.5 else -34))
        else:
            out += [128] * n
    return out


def convert_sounds():
    exe = build_renderer()
    a = iddata.Audio()
    sfxdir = os.path.join(RES, 'sfx')
    os.makedirs(sfxdir, exist_ok=True)
    res = []
    hdr = []
    out = HEADER
    prios = []
    lens = []
    import array
    rendered = []
    for i, nm in enumerate(SOUND_NAMES):
        ch = a.chunk(34 + i)          # STARTADLIBSOUNDS
        length, prio = struct.unpack_from('<IH', ch, 0)
        tmp = os.path.join(HERE, 'build', 'snd%d.bin' % i)
        open(tmp, 'wb').write(ch)
        raw = subprocess.check_output([exe, tmp])
        s16 = array.array('h')
        s16.frombytes(raw)
        rendered.append(s16)
        prios.append(prio)
        lens.append((length + 1) // 2)       # 140 Hz samples -> 70 Hz tics
    peak = max(max(abs(v) for v in s) for s in rendered)
    gain = 28000.0 / peak
    for i, nm in enumerate(SOUND_NAMES):
        s16 = array.array('h', (max(-32768, min(32767, int(v * gain))) for v in rendered[i]))
        pcm = resample(s16, 49716, PCM_RATE)
        while len(pcm) > 1 and abs(pcm[-1] - 128) < 1:
            pcm.pop()
        write_wav(os.path.join(sfxdir, 'al_%s.wav' % nm.lower()), pcm, PCM_RATE)
        res.append('WAV sfxal_%s "sfx/al_%s.wav" XGM2 %d' % (nm.lower(), nm.lower(), PCM_RATE))
        pc = pc_render(a.chunk(i))            # STARTPCSOUNDS
        write_wav(os.path.join(sfxdir, 'pc_%s.wav' % nm.lower()), pc, PCM_RATE)
        res.append('WAV sfxpc_%s "sfx/pc_%s.wav" XGM2 %d' % (nm.lower(), nm.lower(), PCM_RATE))
    out += c_words('sound_priority', prios)
    out += c_words('sound_tics', lens)
    hdr.append('#define NUMSOUNDS %d' % len(SOUND_NAMES))
    hdr.append('extern const u16 sound_priority[NUMSOUNDS];')
    hdr.append('extern const u16 sound_tics[NUMSOUNDS];')
    for i, nm in enumerate(SOUND_NAMES):
        hdr.append('#define %s %d' % (nm, i))
    # intro beep: PC speaker sound(800) for 170 ms (INTRO.EXE screen change)
    n = int(PCM_RATE * 0.170)
    beep = []
    half = PCM_RATE / 800.0 / 2
    for k in range(n):
        beep.append(128 + (34 if int(k / half) % 2 == 0 else -34))
    write_wav(os.path.join(sfxdir, 'beep.wav'), beep, PCM_RATE)
    res.append('WAV sfx_beep "sfx/beep.wav" XGM2 %d' % PCM_RATE)
    # sample pointer tables (sizes from the rescomp header)
    tab = HEADER.replace('#include "gen/assets.h"', '#include "gen/assets.h"\n#include "res_assets.h"')
    for kind in ('al', 'pc'):
        tab += 'const u8 * const snd_%s_data[NUMSOUNDS] = {%s};\n' % (
            kind, ','.join('sfx%s_%s' % (kind, nm.lower()) for nm in SOUND_NAMES))
        tab += 'const u32 snd_%s_len[NUMSOUNDS] = {%s};\n' % (
            kind, ','.join('sizeof(sfx%s_%s)' % (kind, nm.lower()) for nm in SOUND_NAMES))
        hdr.append('extern const u8 * const snd_%s_data[NUMSOUNDS];' % kind)
        hdr.append('extern const u32 snd_%s_len[NUMSOUNDS];' % kind)
    write('soundtab.c', tab)
    return out, hdr, res


