def scale_rows(s):
    """Row mapping identical to BuildCompScale(height = 2*s)."""
    height = 2 * s
    step = (height << 16) // 64
    toppix = (VIEWHEIGHT - height) // 2
    fix = 0
    starts = []
    rows = []      # (src, first_row, last_row_exclusive) clipped
    for src in range(65):
        startpix = fix >> 16
        fix += step
        endpix = fix >> 16
        starts.append(startpix + toppix)
        if src == 64:
            continue
        a, b = startpix + toppix, endpix + toppix
        a2, b2 = max(a, 0), min(b, VIEWHEIGHT)
        if a2 < b2:
            rows.append((src, a2, b2))
    return starts, rows


def convert_scalers():
    asm = ['/* Generated by tools/convert.py: compiled wall scalers.',
           ' * Input: a0 = texture column (64 words), a1 = destination column',
           ' * (rows are 4 bytes apart). Clobbers d0.  scaler_N writes one',
           ' * byte (a 2-pixel column), wscaler_N one word (two columns). */',
           '        .text', '        .align 2']
    for kind, sz in (('scaler', 'b'), ('wscaler', 'w')):
        for s in range(1, MAXSCALE + 1):
            starts, rows = scale_rows(s)
            asm.append('        .globl %s_%d' % (kind, s))
            asm.append('%s_%d:' % (kind, s))
            for src, a, b in rows:
                if b - a == 1:
                    asm.append('        move.%s %d(%%a0),%d(%%a1)' % (sz, src * 2, a * 4))
                else:
                    asm.append('        move.%s %d(%%a0),%%d0' % (sz, src * 2))
                    for r in range(a, b):
                        asm.append('        move.%s %%d0,%d(%%a1)' % (sz, r * 4))
            asm.append('        rts')
        asm.append('        .globl %s_table' % kind)
        asm.append('        .align 2')
        asm.append('%s_table:' % kind)
        asm.append('        .long %s_1' % kind)
        for s in range(1, MAXSCALE + 1):
            asm.append('        .long %s_%d' % (kind, s))
    open(os.path.join(GEN, 'scalers.s'), 'w').write('\n'.join(asm) + '\n')

    # sprite tables: per half-height s, start row of each source pixel (65)
    starts_all = []
    rowsrc = []
    for s in range(0, MAXSCALE + 1):
        st, rows = scale_rows(max(s, 1))
        starts_all += [v for v in st]
        m = [255] * VIEWHEIGHT
        for src, a, b in rows:
            for r in range(a, b):
                m[r] = src
        rowsrc += m
    out = HEADER
    out += c_words('scale_starts', [v & 0xFFFF for v in starts_all], 's16')
    out += c_bytes('scale_rowsrc', rowsrc)
    hdr = ['#define MAXSCALE %d' % MAXSCALE,
           'extern const s16 scale_starts[(MAXSCALE+1)*65];',
           'extern const u8 scale_rowsrc[(MAXSCALE+1)*%d];' % VIEWHEIGHT,
           'typedef void (*ScalerFn)(void);',
           'extern const ScalerFn scaler_table[MAXSCALE+1];']
    # fix signed values
    out = out.replace('const s16 scale_starts', 'const s16 scale_starts')
    vals = ','.join(str(v) for v in starts_all)
    out = HEADER + 'const s16 scale_starts[%d] = {%s};\n' % (len(starts_all), vals) + c_bytes('scale_rowsrc', rowsrc)
    return out, hdr



