def convert_maps():
    m = iddata.Maps()
    out = HEADER
    hdr = []
    n = 0
    names = []
    for i in range(100):
        L = m.level(i)
        if not L:
            break
        n += 1
        p0 = L['planes'][0]
        p2 = L['planes'][2]
        assert max(p0) < 256, 'plane0 > 255'
        out += c_bytes('map%d_p0' % i, p0, static=True)
        out += c_words('map%d_p2' % i, p2, static=True)
        names.append((L['w'], L['h'], L['name']))
    out += 'const MapDef map_defs[NUMMAPDEFS] = {\n'
    for i, (w, h, nm) in enumerate(names):
        out += '  {%d,%d,map%d_p0,map%d_p2,%s},\n' % (w, h, i, i, c_string(nm))
    out += '};\n'
    out += c_bytes('tile_flags', m.tinf[618 - 402:618 - 402 + 216] if False else iddata.linked('maphead')[618:618 + 216])
    hdr.append('#define NUMMAPDEFS %d' % n)
    hdr.append('typedef struct { u16 w, h; const u8 *plane0; const u16 *plane2; const char *name; } MapDef;')
    hdr.append('extern const MapDef map_defs[NUMMAPDEFS];')
    hdr.append('extern const u8 tile_flags[216];')
    return out, hdr


