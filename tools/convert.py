def convert_texts():
    import docs
    hdr = []
    out = HEADER
    help_txt = open(os.path.join(DATA, 'HELP.TXT'), 'rb').read().decode('latin1').replace('\r', '')
    pages = docs.help_pages(help_txt)
    out += 'const char * const help_pages[%d] = {\n' % len(pages)
    for p in pages:
        out += '  ' + c_string(p) + ',\n'
    out += '};\n'
    hdr.append('#define HELP_PAGES %d' % len(pages))
    hdr.append('extern const char * const help_pages[HELP_PAGES];')

    # the START shell's documents, laid out in its 72x20 text window
    data = bytearray()
    index = []
    menu_marks = None
    for f in ['MENU.SHL', 'QUICK.SHL', 'INSTRUCT.SHL', 'PRODUCTS.SHL']:
        t = lzh.load(os.path.join(DATA, f)).decode('latin1').replace('\r', '')
        t = docs.adapt_shell(f, t)
        pages, marks = docs.layout(t)
        if f == 'MENU.SHL':
            menu_marks = marks
        index.append((f.split('.')[0], len(data) // 2880, len(pages)))
        for pg in pages:
            data += docs.page_bytes(pg)
    out += c_bytes('shell_page_data', data)
    hdr.append('#define SHELL_WIN_X %d' % docs.WIN_X)
    hdr.append('#define SHELL_WIN_Y %d' % docs.WIN_Y)
    hdr.append('#define SHELL_WIN_W %d' % docs.WIN_W)
    hdr.append('#define SHELL_WIN_H %d' % docs.WIN_H)
    hdr.append('extern const u8 shell_page_data[%d];' % len(data))
    for nm, first, cnt in index:
        hdr.append('#define DOC_%s_FIRST %d' % (nm, first))
        hdr.append('#define DOC_%s_PAGES %d' % (nm, cnt))
    assert sorted(menu_marks) == [1, 2, 3, 4, 5, 6], menu_marks

    # PRINTFIL.TXT, the catalog's printable information: plain 80 column
    # text, shown on the whole screen (grey on black like DOS' TYPE)
    t = docs.printfil(open(os.path.join(DATA, 'PRINTFIL.TXT'), 'rb').read().decode('latin1').replace('\r', ''))
    pages, _ = docs.layout(t, fg=7, bg=0, WIN_W=80, WIN_H=24)
    pdata = bytearray()
    for pg in pages:
        pdata += docs.page_bytes(pg, fg=7, bg=0, WIN_W=80, WIN_H=24)
    out += c_bytes('printfil_page_data', pdata)
    hdr.append('#define PRINTFIL_PAGES %d' % len(pages))
    hdr.append('extern const u8 printfil_page_data[%d];' % len(pdata))
    out += 'const u8 shell_menu_rows[6] = {%s};\n' % ','.join(str(menu_marks[i][1]) for i in range(1, 7))
    hdr.append('extern const u8 shell_menu_rows[6];')

    # the 4x8 text mode font (used for the shell pages)
    import font4x8
    gl = font4x8.glyphs()
    out += c_bytes('font4x8', [r for g in gl for r in g])
    hdr.append('extern const u8 font4x8[256*8];')
    return out, hdr


