def convert_images(g):
    """Front end pictures -> res/bin/*.bin (APLIB packed by rescomp)."""
    import screens
    bdir = os.path.join(RES, 'bin')
    os.makedirs(bdir, exist_ok=True)
    for f in os.listdir(bdir):
        os.remove(os.path.join(bdir, f))
    shots, order = screens.build(g)
    res = []
    hdr = []
    for sym, pix in shots:
        open(os.path.join(bdir, sym + '.bin'), 'wb').write(screens.pack(pix))
        res.append('BIN %s "bin/%s.bin" 2 2 0 APLIB FALSE' % (sym, sym))
    out = HEADER.replace('#include "gen/assets.h"', '#include "gen/assets.h"\n#include "res_assets.h"')
    out += 'const u8 * const catalog_pages[%d] = {%s};\n' % (len(order), ','.join(order))
    hdr.append('#define CATALOG_COUNT %d' % len(order))
    hdr.append('extern const u8 * const catalog_pages[CATALOG_COUNT];')
    return out, hdr, res


