def box_glyph(up, down, left, right):
    g = [[0] * 4 for _ in range(8)]
    V = {1: [1], 2: [0, 2]}           # vertical line columns
    Hh = {1: [3], 2: [2, 4]}          # horizontal line rows
    hor = left or right
    ver = up or down
    vcols = V[max(up, down)] if ver else [1]
    hrows = Hh[max(left, right)] if hor else [3]
    top, bot = min(hrows), max(hrows)
    lc, rc = min(vcols), max(vcols)
    if up:
        for c in V[up]:
            inner = (left and c == lc) or (right and c == rc)
            end = (top if inner and up == 2 else bot) if hor else (7 if down else 3)
            for r in range(0, end + 1):
                g[r][c] = 1
    if down:
        for c in V[down]:
            inner = (left and c == lc) or (right and c == rc)
            start = (bot if inner and down == 2 else top) if hor else (0 if up else 3)
            for r in range(start, 8):
                g[r][c] = 1
    if left:
        for r in Hh[left]:
            inner = (up and r == top) or (down and r == bot)
            end = (lc if inner and left == 2 else rc) if ver else (3 if right else 1)
            for c in range(0, end + 1):
                g[r][c] = 1
    if right:
        for r in Hh[right]:
            inner = (up and r == top) or (down and r == bot)
            start = (rc if inner and right == 2 else lc) if ver else (0 if left else 1)
            for c in range(start, 4):
                g[r][c] = 1
    return [sum(g[r][c] << (3 - c) for c in range(4)) for r in range(8)]


def glyphs():
    """256 x 8 row masks."""
    out = []
    for code in range(256):
        rows = [0] * 8
        ch = chr(code)
        if ch in G:
            pat = G[ch]
            for i, s in enumerate(pat):
                rows[1 + i] = sum((1 << (3 - c)) for c, v in enumerate(s) if v == '#')
        elif code in BOX:
            rows = box_glyph(*BOX[code])
        elif code == 0xDB:
            rows = [0xF] * 8
        elif code == 0xDC:
            rows = [0] * 4 + [0xF] * 4
        elif code == 0xDF:
            rows = [0xF] * 4 + [0] * 4
        elif code == 0xDD:
            rows = [0xC] * 8
        elif code == 0xDE:
            rows = [0x3] * 8
        elif code == 0xB0:
            rows = [0x8, 0x2] * 4
        elif code == 0xB1:
            rows = [0xA, 0x5] * 4
        elif code == 0xB2:
            rows = [0xD, 0x7] * 4
        elif code in (0x07, 0xF9, 0xFA):        # bullets
            rows = [0, 0, 0, 0x4, 0, 0, 0, 0] if code != 0x07 else [0, 0, 0x4, 0xE, 0x4, 0, 0, 0]
        elif code == 0xFE:
            rows = [0, 0, 0xE, 0xE, 0xE, 0, 0, 0]
        elif code == 0x10:
            rows = [0, 0x8, 0xC, 0xE, 0xC, 0x8, 0, 0]
        elif code == 0x11:
            rows = [0, 0x2, 0x6, 0xE, 0x6, 0x2, 0, 0]
        elif code == 0x18:
            rows = [0, 0x4, 0xE, 0x4, 0x4, 0x4, 0, 0]
        elif code == 0x19:
            rows = [0, 0x4, 0x4, 0x4, 0xE, 0x4, 0, 0]
        elif code == 0x1A:
            rows = [0, 0, 0x2, 0xF, 0x2, 0, 0, 0]
        elif code == 0x1B:
            rows = [0, 0, 0x4, 0xF, 0x4, 0, 0, 0]
        elif code == 0x9C:                      # pound sign
            rows = [0, 0x4, 0xA, 0xC, 0x8, 0xE, 0, 0]
        elif code >= 0x80 and code < 0xB0:
            rows = [0, 0x4, 0xA, 0xE, 0xA, 0xA, 0, 0]  # accented letters: rare
        out.append(rows)
    return out


def render_text_screen(data, out_w=320):
    """BSAVE text screen (char, attr pairs) -> list of 320x200 pixel indices."""
    gl = glyphs()
    pix = [0] * (320 * 200)
    for cy in range(25):
        for cx in range(80):
            ch = data[(cy * 80 + cx) * 2]
            at = data[(cy * 80 + cx) * 2 + 1]
            fg, bg = at & 15, (at >> 4) & 7
            for r in range(8):
                m = gl[ch][r]
                for c in range(4):
                    pix[(cy * 8 + r) * 320 + cx * 4 + c] = fg if m & (8 >> c) else bg
    return pix
